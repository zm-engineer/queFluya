export type Dict = typeof es

const DICTS: Record<Language, Dict> = { ES: es, EN: en }

/** Pick the dictionary for the user's NATIVE language (EN native → English UI). */
export function getDict(nativeLanguage: Language): Dict {
  return DICTS[nativeLanguage]
}

/**
 * Best-effort UI language for logged-out pages (auth/onboarding) from the
 * browser's Accept-Language header. Defaults to Spanish (the app's first
 * language) for anything that isn't clearly English.
 */
export function detectLanguage(acceptLanguage: string | null | undefined): Language {
  if (!acceptLanguage) return 'ES'
  const primary = acceptLanguage.toLowerCase().split(',')[0]?.trim() ?? ''
  return primary.startsWith('en') ? 'EN' : 'ES'
}
